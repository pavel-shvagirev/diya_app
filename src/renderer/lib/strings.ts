/**
 * The main process loads each page with `?lang=ru|en` (the choice in Settings, else the system
 * language); without it (tests, a bare browser) the browser language decides.
 */
function detectLang(): Lang {
  if (typeof window !== 'undefined') {
    const q = new URLSearchParams(window.location.search).get('lang');
    if (q === 'ru' || q === 'en') return q;
  }
  return langFromLocale(typeof navigator !== 'undefined' ? navigator.language : undefined);
}
export const lang: Lang = detectLang();

/** Active dictionary. */
export const t: typeof ru = lang === 'ru' ? ru : en;
export const dictionaries = { ru, en };
